#!/usr/bin/env python3
"""Regenerate OPEN-WORK.md from the Status line under the title of each file in assignments/ and gates/.

usage: open-work.py [checkout]   (default: the current directory, a checkout of coordination)

Writes OPEN-WORK.md in the checkout. Unconfirmed notes are carried over from the existing file,
keyed by path; a path with no note shows its Status line. Files whose status is DONE, META or
a bare pointer are left out.
"""
import datetime, os, re, subprocess, sys

root = sys.argv[1] if len(sys.argv) > 1 else "."
out_path = os.path.join(root, "OPEN-WORK.md")
old = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else ""
notes = dict(re.findall(r"^- `([^`]+)`: (.*)$", old, re.M))
unconfirmed_intro = re.search(r"(?ms)^These files could not be settled.*?(?=^- `)", old)


def title_of(text):
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()[:140]
    return ""


def status_of(text):
    for line in text.splitlines():
        if line.startswith("Status:"):
            return line[len("Status:"):].strip()
    return None


def host_of(text):
    m = re.search(r"[Ii]ntended host[^:\n]*:\s*([^\n]+)", text)
    if not m:
        return "unspecified"
    value = re.split(r"\.\s|;|\s\(", m.group(1))[0].strip().rstrip(".")
    return value or "unspecified"


def short(st):
    return st[:160]


items = {k: [] for k in ("top", "open_a", "open_g", "claimed", "handed", "green", "unconf", "paused")}
for sub in ("assignments", "gates"):
    for name in sorted(os.listdir(os.path.join(root, sub))):
        if not name.endswith(".md"):
            continue
        path = f"{sub}/{name}"
        text = open(os.path.join(root, path), encoding="utf-8").read()
        st = status_of(text)
        if st is None:
            continue
        title = title_of(text)
        if st.startswith("OPEN"):
            items["open_a" if sub == "assignments" else "open_g"].append((host_of(text), path, title, short(st)))
            if re.search(r"^Priority: TOP\b", text, re.M):
                items["top"].append((path, title, short(st)))
        elif st.startswith("PAUSED"):
            items["paused"].append((path, title, short(st)))
        elif st.startswith("CLAIMED"):
            m = re.search(r"claims/[\w.\-]+\.md", st)
            items["claimed"].append((path, title, m.group(0) if m else short(st)))
        elif st.startswith(("HANDED", "NEEDS-OWNER", "GATE FAILED", "GATE NOT GREEN")):
            items["handed"].append((path, title, short(st)))
        elif st.startswith("UNCONFIRMED"):
            items["unconf"].append((path, notes.get(path, short(st))))
        elif st.startswith("GATE GREEN"):
            items["green"].append((path, title, short(st)))

tip = subprocess.run(["git", "-C", root, "rev-parse", "--short=10", "HEAD"], capture_output=True, text=True).stdout.strip()
today = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
counts = (f"Counts at generation: {len(items['open_a'])} open assignments, {len(items['open_g'])} open gate jobs, "
          f"{len(items['claimed'])} claimed files, {len(items['handed'])} handed or waiting on an owner, "
          f"{len(items['green'])} gate green but not marked DONE, {len(items['unconf'])} unconfirmed files.")

lines = [
    "# Open work",
    "",
    "This file lists the pool work that is open, claimed, handed, or unconfirmed on this branch. "
    f"It is generated by `pool/bin/open-work.py` from the Status line under the title of each file in `assignments/` and `gates/` "
    f"(last generated {today}, from coordination tip {tip}). If this file and a job file's own Status line ever disagree, the job file governs.",
    "",
    counts,
    "",
    "## Top priority",
    "",
]
lines += [f"- `{p}`: {t}. Status: {s}" for p, t, s in items["top"]] or ["None.", ""]
lines += ["", "## Paused", ""]
lines += [f"- `{p}`: {t}. Status: {s}" for p, t, s in items["paused"]] or ["None.", ""]
lines += ["", "## Open assignments", ""]


def grouped(rows):
    out = []
    hosts = sorted({r[0] for r in rows})
    if not rows:
        return ["None.", ""]
    for h in hosts:
        out += [f"### Intended host: {h}", ""]
        for _, path, title, st in sorted(r for r in rows if r[0] == h):
            out.append(f"- `{path}`: {title}")
        out.append("")
    return out


lines += grouped(items["open_a"])
lines += ["## Open gate jobs", ""]
lines += grouped(items["open_g"])
lines += ["## Claimed work", ""]
lines += [f"- `{p}`: claim `{c}`. {t}" for p, t, c in items["claimed"]] or ["None."]
lines += ["", "## Handed, needs owner, or gate not green", ""]
lines += [f"- `{p}`: {t}. Status: {s}" for p, t, s in items["handed"]] or ["None."]
lines += ["", "## Gate green, not marked DONE", ""]
lines += [f"- `{p}`: {t}. Status: {s}" for p, t, s in items["green"]] or ["None."]
lines += ["", "## Unconfirmed", ""]
if unconfirmed_intro:
    lines += [unconfirmed_intro.group(0).rstrip(), ""]
else:
    lines += ["These files could not be settled from the records. Each carries `Status: UNCONFIRMED`.", ""]
lines += [f"- `{p}`: {n}" for p, n in items["unconf"]] or ["None."]
lines.append("")

with open(out_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(counts)
